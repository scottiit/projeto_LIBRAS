// Reproducible browser dataset. No Python runtime or pickle deserialization on clients.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
const csv = readFileSync(new URL('../dataset_libras.csv', import.meta.url), 'utf8');
const rows = csv.trim().split(/\r?\n/).slice(1);
const examples = [], counts = {};
function mediaAspect(path) {
  const data = readFileSync(new URL(`../${path}`, import.meta.url));
  if (/\.png$/i.test(path)) return data.readUInt32BE(16) / data.readUInt32BE(20);
  if (/\.mp4$/i.test(path)) {
    let offset = data.indexOf('tkhd');
    while (offset >= 4) {
      const end = offset - 4 + data.readUInt32BE(offset - 4);
      if (end <= data.length && end > offset + 8) {
        const width = data.readUInt32BE(end - 8) / 65536, height = data.readUInt32BE(end - 4) / 65536;
        if (width > 0 && height > 0) return width / height;
      }
      offset = data.indexOf('tkhd', offset + 4);
    }
  } else {
    for (let offset = 2; offset + 9 < data.length;) {
      if (data[offset] !== 255) break;
      const marker = data[offset + 1], length = data.readUInt16BE(offset + 2);
      if ([192, 193, 194].includes(marker)) return data.readUInt16BE(offset + 7) / data.readUInt16BE(offset + 5);
      if (length < 2) break;
      offset += length + 2;
    }
  }
  throw new Error(`Cannot determine image/video aspect ratio: ${path}`);
}
for (const [index, row] of rows.entries()) {
  const values = row.split(','), label = values.pop()?.trim().toUpperCase();
  const coordinates = values.map(Number);
  if (!/^[A-Z]$/.test(label) || coordinates.length !== 63 || !coordinates.every(Number.isFinite)) throw new Error(`Invalid dataset row ${index + 2}`);
  counts[label] = (counts[label] ?? 0) + 1;
  if (!['J', 'X', 'Z'].includes(label)) examples.push({ label, coordinates: coordinates.map(value => Number(value.toFixed(7))) });
}
const references = {};
for (const label of Object.keys(counts)) {
  const directory = `Libras-20260913T224959Z-1-001/${label.toLowerCase()}`;
  const filename = readdirSync(new URL(`../${directory}/`, import.meta.url)).find(name => /\.(jpg|jpeg|png|mp4)$/i.test(name));
  if (filename) references[label] = `${directory}/${filename}`;
}
const metadata = { version: 1, sha256: createHash('sha256').update(csv).digest('hex'), counts, staticClasses: [...new Set(examples.map(example => example.label))].sort(), limitations: 'Very small single-source dataset; no independent accuracy estimate; no numeral samples.' };
for (const example of examples) example.aspectRatio = mediaAspect(references[example.label]);
writeFileSync(new URL('../js/dataset.js', import.meta.url), `// Generated by node scripts/export-dataset.js from dataset_libras.csv.\nexport const DATASET_METADATA = ${JSON.stringify(metadata)};\nexport const SIGN_REFERENCES = ${JSON.stringify(references)};\nexport const SIGN_EXAMPLES = ${JSON.stringify(examples)};\n`);
console.log(JSON.stringify({ rows: rows.length, exported: examples.length, counts }, null, 2));
